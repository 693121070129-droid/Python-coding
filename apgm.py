def circle_area():
    print("** โปรแกรมหารัศมีวงกรม **")
    r = int(input("ระบุรัศมี : "))
    pi = 3.1415928
    return pi * (r ** 2)

def rectangle_area():
    print("** โปรแกรมหารัศมีสี่เหลี่ยม **")
    h = int(input("ป้อนความสูง :"))
    w = int(input("ป้อนความกว้าง : "))
    return h * w

